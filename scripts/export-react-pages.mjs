import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const siteDir = path.join(root, 'site')
const outFile = path.join(root, 'src', 'generated', 'pages.ts')
const base = '/yellowteco'

const pageFiles = [
  { file: 'index.html', route: '/', title: 'AI Agents for CX and EX Automation - Yellowteco' },
  { file: path.join('pricing', 'index.html'), route: '/pricing', title: 'Pricing - Yellowteco' },
  { file: path.join('investors', 'index.html'), route: '/investors', title: 'Investors - Yellowteco' },
  {
    file: path.join('request-demo', 'index.html'),
    route: '/request-demo',
    title: 'Request a Demo - Yellowteco',
  },
  { file: '404.html', route: '/404', title: 'Page Not Found - Yellowteco' },
]

function absAsset(url) {
  if (!url) return url
  if (url.startsWith('//')) return `https:${url}`
  if (url.startsWith('./assets/')) return `${base}/assets/${url.slice('./assets/'.length)}`
  if (url.startsWith('assets/')) return `${base}/assets/${url.slice('assets/'.length)}`
  return url
}

function extract(html) {
  const bodyTag = html.match(/<body([^>]*)>/i)?.[1] ?? ''
  const bodyClass = /class=["']([^"']*)["']/i.exec(bodyTag)?.[1] ?? ''
  const styles = [...html.matchAll(/<style[^>]*>[\s\S]*?<\/style>/gi)].map((m) => m[0]).join('\n')

  const cssHrefs = [
    ...html.matchAll(/<link[^>]+href=["']([^"']+)["'][^>]*>/gi),
  ]
    .map((m) => absAsset(m[1]))
    .filter((href) => /\.css(\?|$)/i.test(href) || href.includes('css'))

  const scriptSrcs = [
    ...html.matchAll(/<script[^>]+src=["']([^"']+)["'][^>]*>/gi),
  ]
    .map((m) => absAsset(m[1]))
    .filter(Boolean)

  // Keep HubSpot / demo form bootstrap that cannot run via innerHTML
  const inlineScripts = [...html.matchAll(/<script(?![^>]*\bsrc=)[^>]*>([\s\S]*?)<\/script>/gi)]
    .map((m) => m[1].trim())
    .filter((code) => /hbspt\.forms\.create|yellow-hubspot|requestdemoFormSubmitted/i.test(code))

  let body = html.match(/<body[^>]*>([\s\S]*)<\/body>/i)?.[1] ?? ''
  // Scripts cannot run via innerHTML; React shell loads them explicitly
  body = body.replace(/<script[\s\S]*?<\/script>/gi, '')
  body = body.replace(/(["'])\.\/assets\//g, `$1${base}/assets/`)
  body = body
    .replaceAll(`href="${base}/pricing/"`, `href="${base}/pricing"`)
    .replaceAll(`href="${base}/investors/"`, `href="${base}/investors"`)
    .replaceAll(`href="${base}/request-demo/"`, `href="${base}/request-demo"`)
    .replaceAll(`href="${base}/index.html"`, `href="${base}/"`)

  return {
    bodyClass,
    styles,
    cssHrefs: [...new Set(cssHrefs)],
    scriptSrcs: [...new Set(scriptSrcs)],
    inlineScripts,
    body: body.trim(),
  }
}

const pages = []
for (const page of pageFiles) {
  const full = path.join(siteDir, page.file)
  if (!fs.existsSync(full)) {
    console.warn('missing', page.file)
    continue
  }
  const raw = fs.readFileSync(full, 'utf8')
  pages.push({
    route: page.route,
    title: page.title,
    ...extract(raw),
  })
  console.log('exported', page.route)
}

fs.mkdirSync(path.dirname(outFile), { recursive: true })

const serialized = pages
  .map(
    (page) => `  {
    route: ${JSON.stringify(page.route)},
    title: ${JSON.stringify(page.title)},
    bodyClass: ${JSON.stringify(page.bodyClass)},
    styles: ${JSON.stringify(page.styles)},
    cssHrefs: ${JSON.stringify(page.cssHrefs)},
    scriptSrcs: ${JSON.stringify(page.scriptSrcs)},
    inlineScripts: ${JSON.stringify(page.inlineScripts)},
    body: ${JSON.stringify(page.body)},
  }`,
  )
  .join(',\n')

const contents = `/* Auto-generated by scripts/export-react-pages.mjs — do not edit */
export type YellowtecoPage = {
  route: string
  title: string
  bodyClass: string
  styles: string
  cssHrefs: string[]
  scriptSrcs: string[]
  inlineScripts: string[]
  body: string
}

export const pages: YellowtecoPage[] = [
${serialized}
]

export function findPage(pathname: string): YellowtecoPage {
  const clean = pathname.replace(/\\/$/, '') || '/'
  return (
    pages.find((page) => page.route === clean || page.route === pathname) ??
    pages.find((page) => page.route === '/404')!
  )
}
`

fs.writeFileSync(outFile, contents)
console.log('wrote', path.relative(root, outFile), `(${pages.length} pages)`)
